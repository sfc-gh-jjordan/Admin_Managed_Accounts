-- ---------------------------------------------------------------------
-- Durable operation queue
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS OPERATIONS (
    OPERATION_ID        VARCHAR DEFAULT UUID_STRING() PRIMARY KEY,
    ACCOUNT_ID          VARCHAR NOT NULL,
    USERNAME            VARCHAR,
    ACTION              VARCHAR NOT NULL,
      -- ONBOARD_USER | ADD_ROLES | SET_MANAGED_ROLES | DISABLE_USER | REENABLE_USER
      -- ISSUE_PASSWORD_LINK | ENROLL_MFA | RECONCILE_ACCOUNT | PREFLIGHT
      -- PROVISION_INTERNAL_ADMIN | GRANT_ACCOUNTADMIN | REVOKE_ACCOUNTADMIN | DISABLE_INTERNAL_ADMIN
      -- CREATE_ROLE (from CSV import; USERNAME is NULL)
    ACTION_FAMILY       VARCHAR DEFAULT 'CUSTOMER',   -- CUSTOMER | PRIVILEGED | SYSTEM
    PAYLOAD             VARIANT,                      -- normalized, immutable after approval
    PAYLOAD_SHA256      VARCHAR,
    BATCH_ID            VARCHAR,
    ACCESS_ID           VARCHAR,                      -- ADMIN_ACCOUNT_ACCESS link
    REGISTRY_VERSION    NUMBER,
    CATALOG_VERSION     NUMBER,
    DEPENDS_ON          ARRAY,                        -- OPERATION_IDs that must SUCCEED first
    STATUS              VARCHAR DEFAULT 'PENDING_APPROVAL',
      -- PENDING_APPROVAL|QUEUED|RUNNING|SUCCEEDED|PARTIAL|FAILED|BLOCKED|CANCELLED
    REQUESTED_BY        VARCHAR,
    REQUESTED_AT        TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    REASON              VARCHAR,
    TICKET              VARCHAR,
    APPROVED_BY         VARCHAR,
    APPROVED_AT         TIMESTAMP_LTZ,
    CLAIMED_BY          VARCHAR,                      -- worker run id
    CLAIMED_AT          TIMESTAMP_LTZ,
    ATTEMPTS            NUMBER DEFAULT 0,
    MAX_ATTEMPTS        NUMBER DEFAULT 5,
    NEXT_ATTEMPT_AT     TIMESTAMP_LTZ,
    LAST_ERROR          VARCHAR,                      -- redacted
    COMPLETED_AT        TIMESTAMP_LTZ,
    SEQUENCE_NO         NUMBER AUTOINCREMENT START 1 INCREMENT 1 ORDER
);

