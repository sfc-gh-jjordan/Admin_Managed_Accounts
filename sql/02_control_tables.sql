-- ---------------------------------------------------------------------
-- Views used by the Streamlit app
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW V_USER_INVENTORY AS
SELECT  u.ACCOUNT_ID,
        a.DISPLAY_NAME                  AS ACCOUNT_DISPLAY_NAME,
        u.USERNAME, u.EMAIL, u.FIRST_NAME, u.LAST_NAME,
        u.IDENTITY_CLASS, u.IS_MANAGED,
        u.DESIRED_STATE, u.ONBOARDING_STATE,
        u.OBSERVED_EXISTS, u.OBSERVED_DISABLED, u.OBSERVED_TYPE,
        u.DESIRED_DEFAULT_ROLE, u.OBSERVED_DEFAULT_ROLE,
        u.OBSERVED_AUTH_POLICY, u.MFA_EVIDENCE,
        d.DESIRED_ROLES, o.OBSERVED_ROLES,
        u.DRIFT_FLAGS,
        u.LAST_VERIFIED_AT,
        IFF(u.LAST_VERIFIED_AT IS NULL OR u.LAST_VERIFIED_AT < DATEADD(hour, -24, CURRENT_TIMESTAMP()), TRUE, FALSE) AS IS_STALE,
        lo.STATUS                       AS LAST_OPERATION_STATUS,
        lo.ACTION                       AS LAST_OPERATION_ACTION
FROM USER_CONTROL u
LEFT JOIN CUSTOMER_ACCOUNTS a USING (ACCOUNT_ID)
LEFT JOIN (SELECT ACCOUNT_ID, USERNAME, ARRAY_AGG(ROLE_NAME) WITHIN GROUP (ORDER BY ROLE_NAME) AS DESIRED_ROLES
           FROM USER_ROLE_DESIRED GROUP BY 1,2) d USING (ACCOUNT_ID, USERNAME)
LEFT JOIN (SELECT ACCOUNT_ID, USERNAME, ARRAY_AGG(ROLE_NAME) WITHIN GROUP (ORDER BY ROLE_NAME) AS OBSERVED_ROLES
           FROM USER_ROLE_OBSERVED GROUP BY 1,2) o USING (ACCOUNT_ID, USERNAME)
LEFT JOIN (SELECT ACCOUNT_ID, USERNAME, STATUS, ACTION
           FROM OPERATIONS
           QUALIFY ROW_NUMBER() OVER (PARTITION BY ACCOUNT_ID, USERNAME ORDER BY REQUESTED_AT DESC) = 1) lo
       USING (ACCOUNT_ID, USERNAME);

CREATE OR REPLACE VIEW V_OVERVIEW_METRICS AS
SELECT
  (SELECT COUNT(*) FROM CUSTOMER_ACCOUNTS)                                               AS ACCOUNTS_TOTAL,
  (SELECT COUNT(*) FROM CUSTOMER_ACCOUNTS WHERE IS_ENABLED AND NOT IS_PAUSED)           AS ACCOUNTS_ACTIVE,
  (SELECT COUNT(*) FROM CUSTOMER_ACCOUNTS WHERE IS_PAUSED)                              AS ACCOUNTS_PAUSED,
  (SELECT COUNT(*) FROM USER_CONTROL WHERE IS_MANAGED AND OBSERVED_DISABLED = FALSE)    AS MANAGED_ENABLED,
  (SELECT COUNT(*) FROM USER_CONTROL WHERE IS_MANAGED AND OBSERVED_DISABLED = TRUE)     AS MANAGED_DISABLED,
  (SELECT COUNT(*) FROM USER_CONTROL WHERE NOT IS_MANAGED)                              AS UNMANAGED_USERS,
  (SELECT COUNT(*) FROM OPERATIONS WHERE STATUS = 'PENDING_APPROVAL')                   AS PENDING_APPROVALS,
  (SELECT COUNT(*) FROM OPERATIONS WHERE STATUS IN ('QUEUED','RUNNING'))                AS IN_FLIGHT,
  (SELECT COUNT(*) FROM OPERATIONS WHERE STATUS IN ('FAILED','PARTIAL','BLOCKED'))      AS FAILED_OPS,
  (SELECT COUNT(*) FROM USER_CONTROL WHERE ONBOARDING_STATE = 'PROVISIONED_PENDING_HANDOFF') AS HANDOFF_PENDING,
  (SELECT COUNT(*) FROM USER_CONTROL WHERE MFA_EVIDENCE = 'REQUIRED_NOT_YET_OBSERVED')  AS MFA_PENDING,
  (SELECT COUNT(*) FROM USER_CONTROL WHERE ARRAY_SIZE(DRIFT_FLAGS) > 0)                 AS DRIFTED_USERS,
  (SELECT COUNT(*) FROM USER_CONTROL
     WHERE LAST_VERIFIED_AT IS NULL OR LAST_VERIFIED_AT < DATEADD(hour,-24,CURRENT_TIMESTAMP())) AS STALE_USERS;

-- Secure view for handoff (approvers only)
CREATE OR REPLACE SECURE VIEW V_HANDOFF_PENDING AS
SELECT HANDOFF_ID, OPERATION_ID, ACCOUNT_ID, USERNAME, LINK_TYPE, LINK_VALUE, CREATED_AT, EXPIRES_AT
FROM HANDOFF_VAULT
WHERE DELIVERED_AT IS NULL AND EXPIRES_AT > CURRENT_TIMESTAMP();

