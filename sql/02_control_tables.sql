-- ---------------------------------------------------------------------
-- Account registry: one row per managed Snowflake account in the org
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS CUSTOMER_ACCOUNTS (
    ACCOUNT_ID              VARCHAR      NOT NULL PRIMARY KEY,   -- short stable key, e.g. 'CPG_ACME' ([A-Z0-9_])
    CUSTOMER_ID             VARCHAR,
    DISPLAY_NAME            VARCHAR,
    ORGANIZATION_NAME       VARCHAR,
    ACCOUNT_NAME            VARCHAR,                             -- org account name
    ACCOUNT_LOCATOR         VARCHAR,
    REGION                  VARCHAR,
    CLOUD                   VARCHAR,
    SQL_API_HOST            VARCHAR,                             -- verified, e.g. myorg-acme.snowflakecomputing.com
    JWT_ACCOUNT_IDENTIFIER  VARCHAR,                             -- e.g. MYORG-ACME (org-account, '.' -> '-')
    EXPECTED_ACCOUNT_LOCATOR VARCHAR,                            -- preflight: CURRENT_ACCOUNT() must equal this
    SERVICE_USER            VARCHAR      DEFAULT 'SVC_ACCT_ADMIN',
    EXEC_ROLE               VARCHAR      DEFAULT 'ACCOUNTADMIN', -- role used on every SQL API request
    EXEC_WAREHOUSE          VARCHAR,                             -- optional; SHOW/DDL need none
    SECRET_NAME             VARCHAR,                             -- ACCT_ADMIN_DB.SECRETS.<..>  (reference only)
    SECRET_VERSION          NUMBER       DEFAULT 1,
    PUBLIC_KEY_FP           VARCHAR,                             -- SHA256:... fingerprint registered on target
    WORKER_PROCEDURE        VARCHAR,                             -- ACCT_ADMIN_DB.WORKER.EXEC_<ACCOUNT_ID>
    EAI_NAME                VARCHAR,
    APPROVED_EMAIL_DOMAINS  ARRAY,
    PROTECTED_USERS         ARRAY,                               -- never touched by customer workflow
    CUSTOMER_AUTH_POLICY    VARCHAR      DEFAULT 'ADMIN_POLICIES.POLICIES.CPG_HUMAN_MFA_V1',
    INTERNAL_AUTH_POLICY    VARCHAR      DEFAULT 'ADMIN_POLICIES.POLICIES.INTERNAL_ADMIN_MFA_V1',
    POLICY_VERSION          VARCHAR      DEFAULT 'V1',
    INTERNAL_DEFAULT_ROLE   VARCHAR      DEFAULT 'PUBLIC',       -- low-privilege default for internal admins
    IS_ENABLED              BOOLEAN      DEFAULT FALSE,          -- worker refuses disabled accounts
    IS_PAUSED               BOOLEAN      DEFAULT FALSE,          -- circuit breaker
    PAUSE_REASON            VARCHAR,
    CONSECUTIVE_FAILURES    NUMBER       DEFAULT 0,
    BOOTSTRAP_STATUS        VARCHAR      DEFAULT 'NOT_BOOTSTRAPPED', -- NOT_BOOTSTRAPPED|CONNECTIVITY_READY|VERIFIED|ERROR
    LAST_PREFLIGHT_AT       TIMESTAMP_LTZ,
    LAST_PREFLIGHT_RESULT   VARIANT,
    REGISTRY_VERSION        NUMBER       DEFAULT 1,              -- bumped on any change; bound into approvals
    DISCOVERED_FROM_ORG     BOOLEAN      DEFAULT FALSE,
    CREATED_AT              TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT              TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_BY              VARCHAR      DEFAULT CURRENT_USER()
);

-- ---------------------------------------------------------------------
-- Allowed roles per account
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ROLE_CATALOG (
    ACCOUNT_ID          VARCHAR NOT NULL,
    ROLE_NAME           VARCHAR NOT NULL,
    IS_DEFAULT_ELIGIBLE BOOLEAN DEFAULT TRUE,
    APPROVAL_CLASS      VARCHAR DEFAULT 'STANDARD',   -- STANDARD | ELEVATED | BLOCKED
    REVIEW_NOTES        VARCHAR,
    CATALOG_VERSION     NUMBER  DEFAULT 1,
    IS_ACTIVE           BOOLEAN DEFAULT TRUE,
    UPDATED_AT          TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (ACCOUNT_ID, ROLE_NAME)
);

-- Roles that may NEVER appear in customer CSVs regardless of catalog
CREATE TABLE IF NOT EXISTS BLOCKED_ROLES (ROLE_NAME VARCHAR PRIMARY KEY);
MERGE INTO BLOCKED_ROLES t USING (
    SELECT column1 AS ROLE_NAME FROM VALUES
      ('ACCOUNTADMIN'),('SECURITYADMIN'),('USERADMIN'),('SYSADMIN'),('ORGADMIN'),('GLOBALORGADMIN')
) s ON t.ROLE_NAME = s.ROLE_NAME
WHEN NOT MATCHED THEN INSERT (ROLE_NAME) VALUES (s.ROLE_NAME);

